-- Empty test databases do not contain this data. Once any snapshot field exists,
-- refuse a partial, changed, or not-yet-cleaned dataset rather than guessing.
do $$
declare
  present integer;
begin
  select count(*) into present from public.registry_fields f
    where f.id in (select field_id from category_seed_mapping)
       or f.id in ('3dfb2369-695b-47ed-9a52-d255a245bfa3',
         '4a507601-3355-49a6-9096-8d86639ddad4');
  if present = 0 then return; end if;
  if exists (select 1 from public.registry_fields
      where id = '3dfb2369-695b-47ed-9a52-d255a245bfa3') then
    raise exception 'Source-field cleanup is required before category seeding';
  end if;
  if (select count(*) from public.registry_fields) <> 125 or (select md5(string_agg(
      f.id::text || chr(31) || f.registry_id::text || chr(31) || f.source_text,
      chr(30) order by f.id)) from public.registry_fields f) <> '74b33ac9e271c300d8d1edf9ffda78a6' then
    raise exception 'Source-field snapshot differs; review category seed before applying';
  end if;
  if exists (select 1 from category_seed_mapping m
      join public.categories c on c.parent_id is null and lower(trim(c.name)) = lower(trim(m.root_name))
      where not c.active) then
    raise exception 'A category in the proposed mapping is inactive';
  end if;
end;
$$;

insert into public.categories (name)
select distinct m.root_name from category_seed_mapping m
where exists (select 1 from public.registry_fields f join category_seed_mapping m2 on m2.field_id = f.id)
on conflict do nothing;

insert into public.categories (name, parent_id)
select distinct m.child_name, root.id from category_seed_mapping m
join public.categories root on root.parent_id is null and lower(trim(root.name)) = lower(trim(m.root_name))
where exists (select 1 from public.registry_fields f join category_seed_mapping m2 on m2.field_id = f.id)
on conflict do nothing;

do $$
begin
  if exists (select 1 from category_seed_mapping m
      join public.categories root on root.parent_id is null and lower(trim(root.name)) = lower(trim(m.root_name))
      join public.categories child on child.parent_id = root.id and lower(trim(child.name)) = lower(trim(m.child_name))
      where not child.active and exists (select 1 from public.registry_fields f
        join category_seed_mapping m2 on m2.field_id = f.id)) then
    raise exception 'A subcategory in the proposed mapping is inactive';
  end if;
end;
$$;

-- Existing manual category links are retained; no legacy assignment is overwritten.
insert into public.registry_field_categories (registry_field_id, category_id)
select m.field_id, child.id from category_seed_mapping m
join public.registry_fields f on f.id = m.field_id
join public.categories root on root.parent_id is null and lower(trim(root.name)) = lower(trim(m.root_name))
join public.categories child on child.parent_id = root.id and lower(trim(child.name)) = lower(trim(m.child_name))
on conflict (registry_field_id, category_id) do nothing;
