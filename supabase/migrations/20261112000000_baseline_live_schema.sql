-- Baseline: the live schema of project jerusalem-consultants as of 2026-11-12,
-- exported read-only from the catalog because it was created in the dashboard and
-- never recorded as a migration. On the live project this migration is marked as
-- applied (supabase migration repair --status applied 20261112000000) and not run.

create table public.suppliers (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) between 1 and 160),
  field text not null check (length(trim(field)) between 1 and 500),
  registry text not null,
  source_url text,
  source_page integer check (source_page is null or source_page > 0),
  email text,
  phone text,
  note text,
  review_status text not null default 'needs_review'
    check (review_status in ('needs_review', 'verified')),
  created_at timestamptz not null default now(),
  created_by uuid references auth.users (id)
);

create table public.activity_events (
  id bigint generated by default as identity primary key,
  actor_id uuid not null references auth.users (id),
  event_type text not null check (event_type in ('page_view', 'search', 'filter', 'action')),
  details jsonb not null default '{}'::jsonb check (octet_length(details::text) <= 4000),
  created_at timestamptz not null default now()
);

alter table public.suppliers enable row level security;
alter table public.activity_events enable row level security;

revoke all on public.suppliers, public.activity_events from anon, authenticated;
grant select, insert, update on public.suppliers to authenticated;
grant select, insert on public.activity_events to authenticated;

create policy supplier_admin_select on public.suppliers for select to authenticated
  using (((auth.jwt() -> 'app_metadata') ->> 'role') = 'supplier_admin');
create policy supplier_admin_insert on public.suppliers for insert to authenticated
  with check (
    ((auth.jwt() -> 'app_metadata') ->> 'role') = 'supplier_admin'
    and created_by = auth.uid()
  );
create policy supplier_admin_update on public.suppliers for update to authenticated
  using (((auth.jwt() -> 'app_metadata') ->> 'role') = 'supplier_admin')
  with check (((auth.jwt() -> 'app_metadata') ->> 'role') = 'supplier_admin');

create policy activity_admin_read on public.activity_events for select to authenticated
  using (((auth.jwt() -> 'app_metadata') ->> 'role') = 'supplier_admin');
create policy activity_insert_own on public.activity_events for insert to authenticated
  with check (
    actor_id = auth.uid()
    and ((auth.jwt() -> 'app_metadata') ->> 'role') = 'supplier_admin'
  );

-- Created by the dashboard option that enables RLS on every new public table.
create function public.rls_auto_enable()
returns event_trigger
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  cmd record;
  tbl name;
begin
  for cmd in
    select * from pg_event_trigger_ddl_commands()
    where command_tag in ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      and object_type in ('table', 'partitioned table')
  loop
    if cmd.schema_name = 'public' then
      begin
        select c.relname into tbl from pg_catalog.pg_class c where c.oid = cmd.objid;
        execute format('alter table if exists %I.%I enable row level security',
          cmd.schema_name, tbl);
      exception
        when others then
          raise log 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      end;
    end if;
  end loop;
end;
$$;

create event trigger ensure_rls on ddl_command_end execute function public.rls_auto_enable();
